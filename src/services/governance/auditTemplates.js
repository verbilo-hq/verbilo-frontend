/** Lookup: returns the audit template for a given audit-type ID, or null. */
export function getAuditTemplate(auditTypeId) {
  return AUDIT_TEMPLATES.find((t) => t.id === auditTypeId) ?? null;
}

/** Lookup: returns all audit templates for a given pack. */
export function listAuditTemplatesForPack(packKey) {
  return AUDIT_TEMPLATES.filter((t) => t.packKey === packKey);
}
